# -*- coding: utf-8 -*-
"""
省令の条文(statute)を1件目として入れる。

2026-08-23。指定居宅サービス等の事業の人員、設備及び運営に関する基準
(平成11年3月31日 厚生省令第37号)の条文に到達した。

分かったこと:
  第30条の2 業務継続計画の策定等
    第2項に「研修及び訓練を定期的に実施しなければならない」とある。
    二次資料だけを見ていたときは未確認にしていた要件が、条文に存在した。
  第37条の2 虐待の防止
    委員会は「定期的に開催」、研修は「定期的に実施」。
    条文に「年1回以上」という頻度は無い。

    二次資料は「訪問看護は年1回以上」としていた。ヒアリングの設問文にも
    その断定を書いていたが、条文には無い。頻度は解釈通知の側にあると思われる。
    設問文からは既に外してある。ここでは、条文に無いことを記録する。

注意して残すこと:
  取得できた条文は訪問介護の章のものである。訪問看護へは準用規定を通じて
  適用されるはずだが、その準用の条番号は今回取得できていない。
  「訪問看護にも同じ条文が適用される」と書くには、その一歩が足りない。
  足りないまま書けば、条文を引いた分だけ、間違いが強く見えるようになる。
"""

import io, json, os, sys

P = os.path.abspath(os.environ.get("JHNRD_DATA",
    os.path.join(os.path.dirname(os.path.abspath(__file__)), "data", "rules_2024.json")))

SOURCE_ID = "mhlw-shorei-h11-37"
SOURCE = {
    "title": "指定居宅サービス等の事業の人員、設備及び運営に関する基準 (平成11年3月31日 厚生省令第37号)",
    "publisher": "厚生労働省",
    "url": "https://www.mhlw.go.jp/web/t_doc?dataId=82999404&dataType=0&pageNo=1",
    "tier": "statute",
    "retrieved_at": "2026-08-23",
    "note": ("省令の条文そのもの。ただし今回取得できたのは訪問介護の章の条文である。"
             "訪問看護への準用の条番号は未取得。準用が確認できるまで、"
             "訪問看護に同じ条文が適用されると断定しない。"),
}


def main():
    db = json.load(io.open(P, encoding="utf-8"))
    db["sources"][SOURCE_ID] = SOURCE
    db["version"] = "2024-kaitei.seed.3"

    for it in db["items"]:
        if it["id"] == "genzan-bcp":
            it["statute"] = {
                "article": "第30条の2 業務継続計画の策定等",
                "source_ref": [SOURCE_ID],
                "text_1": ("感染症や非常災害の発生時において、利用者に対する指定訪問介護の提供を"
                           "継続的に実施するための、及び非常時の体制で早期の業務再開を図るための計画"
                           "(以下「業務継続計画」という。)を策定し、当該業務継続計画に従い必要な措置を"
                           "講じなければならない。"),
                "text_2": ("訪問介護員等に対し、業務継続計画について周知するとともに、"
                           "必要な研修及び訓練を定期的に実施しなければならない。"),
                "text_3": ("定期的に業務継続計画の見直しを行い、必要に応じて業務継続計画の変更を"
                           "行うものとする。"),
                "caveat": ("この条文は訪問介護の章のもの。訪問看護への準用の条番号は未取得。"),
            }
            for r in it["requirements"]:
                if r["id"] == "bcp-train":
                    r["confirmed"] = False
                    r["unconfirmed_reason"] = (
                        "省令第30条の2第2項に「必要な研修及び訓練を定期的に実施しなければならない」"
                        "とあり、要件としては条文に存在する。ただし取得できた条文は訪問介護の章のもので、"
                        "訪問看護への準用の条番号を確認できていない。準用が確認できるまで未確認とする。")
                    r["source_ref"] = [SOURCE_ID]
            it["requirements"].append({
                "id": "bcp-review",
                "text": "業務継続計画の見直しを定期的に行っていること(省令第30条の2第3項)",
                "ask": "q_nv_bcp_plan",
                "confirmed": False,
                "unconfirmed_reason": "条文には存在するが、訪問看護への準用の条番号が未確認。",
                "source_ref": [SOURCE_ID],
            })
            it["sources"].insert(0, SOURCE_ID)

        if it["id"] == "genzan-gyakutai":
            it["statute"] = {
                "article": "第37条の2 虐待の防止",
                "source_ref": [SOURCE_ID],
                "items": [
                    ("一", "当該指定訪問介護事業所における虐待の防止のための対策を検討する委員会"
                           "(テレビ電話装置等を活用して行うことができるものとする。)を定期的に開催するとともに、"
                           "その結果について、訪問介護員等に周知徹底を図ること。"),
                    ("二", "当該指定訪問介護事業所における虐待の防止のための指針を整備すること。"),
                    ("三", "当該指定訪問介護事業所において、訪問介護員等に対し、"
                           "虐待の防止のための研修を定期的に実施すること。"),
                    ("四", "前三号に掲げる措置を適切に実施するための担当者を置くこと。"),
                ],
                "frequency_finding": ("条文は委員会も研修も「定期的に」とだけ書いている。"
                                      "「年1回以上」という頻度は、この条文には無い。"),
                "caveat": "この条文は訪問介護の章のもの。訪問看護への準用の条番号は未取得。",
            }
            for d in it.get("detail_unconfirmed", []):
                if "年1回以上" in d["text"]:
                    d["unconfirmed_reason"] = (
                        "省令第37条の2の条文には「定期的に」とあるのみで、「年1回以上」という頻度は無い。"
                        "この頻度は解釈通知の側にあると思われるが、未取得。"
                        "ヒアリングの設問文からは、この断定を既に外してある。")
                    d["source_ref"] = ["kaipoke-gyakutai", SOURCE_ID]
                if "委員会の開催頻度" in d["text"]:
                    d["unconfirmed_reason"] = (
                        "省令第37条の2第一号は「定期的に開催」とのみ規定。具体的な頻度は条文に無い。")
                    d["source_ref"] = [SOURCE_ID]
            it["statute_requirement_texts_note"] = (
                "requirements の text は、条文の文言に合わせて『周知徹底を図ること』まで含めるべきだが、"
                "訪問看護への準用が確認できるまでは、訪問介護向けの文言をそのまま訪問看護の要件として"
                "書き写さない。")
            it["sources"].insert(0, SOURCE_ID)

    db["known_gaps"].insert(0, {
        "gap": "取得できた省令の条文は訪問介護の章のもので、訪問看護への準用の条番号を確認できていない。",
        "consequence": "訪問看護に同じ条文がそのまま適用される、とはまだ書けない。条文を引いた分だけ、間違えたときに強く見える。",
        "next": "厚生省令第37号の訪問看護の章(第4章)にある準用規定の条番号を取得する。",
    })

    io.open(P, "w", encoding="utf-8").write(
        json.dumps(db, ensure_ascii=False, indent=2) + "\n")
    print("省令の条文を1件目の statute として追加しました。版 -> " + db["version"])


if __name__ == "__main__":
    main()
