def main():
    apply = "--apply" in sys.argv
    db = json.load(io.open(P, encoding="utf-8"))
    qs = db.get("questions", [])
    have = {q["id"] for q in qs}
    base = max([int(q.get("order", 0)) for q in qs] or [0]) + 1

    add, skip = [], []
    for n, q in enumerate(NEW):
        if q["id"] in have:
            skip.append(q["id"]); continue
        e = dict(q); e["order"] = base + n
        e["not_a_source"] = True
        e["note"] = NOTE
        add.append(e)

    print("いまの設問: %d 問 (うち field %d)" %
          (len(qs), sum(1 for q in qs if q.get("purpose") == "field")))
    print("足すもの  : %d 問" % len(add))
    for e in add:
        print("  %-20s w=%-2d 穴: %s" % (e["id"], e["w"], e["fills_gap"][:52]))
        print("  %-20s      得るもの: %s" % ("", e["gives"][:60]))
    if skip:
        print("既にあるので飛ばす: %s" % skip)

    if not apply:
        print("\n(--apply が無いので、まだ書いていません)")
        return

    db["questions"] = qs + add
    db["version"] = "2024-kaitei.seed.8"
    io.open(P, "w", encoding="utf-8").write(json.dumps(db, ensure_ascii=False, indent=2) + "\n")
    print("\n書きました。版 -> %s / 設問 %d 問" % (db["version"], len(db["questions"])))


if __name__ == "__main__":
    main()
